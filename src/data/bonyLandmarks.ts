function bilateralPair(spec: BilateralLandmarkSpec): [BonyLandmarkExtended, BonyLandmarkExtended] {
  const geom = LANDMARK_GEOM_SPECS[spec.baseId];
  const [rx, ry, rz] = geom ? geom.targetPos : spec.rPosition;
  const rEnd = geom?.targetEnd;
  const rNorm = geom?.desiredNormal;
  const zoneRadius = geom?.zoneRadius ?? 0.013;
  const minNormalDot = geom?.minNormalDot ?? 0.38;

  const common = {
    boneId: spec.boneId,
    boneNamePl: spec.boneNamePl,
    boneNameEn: spec.boneNameEn,
    ...(spec.structureId ? { structureId: spec.structureId } : {}),
    namePl: spec.namePl,
    nameEn: spec.nameEn,
    bilingualName: spec.bilingualName,
    type: spec.type,
    attachedMuscles: spec.attachedMuscles,
    clinicalNotes: spec.clinicalNotes,
    zoneRadius,
    minNormalDot,
  };
  return [
    {
      id: `${spec.baseId}_r`,
      ...common,
      parentMesh: spec.rParentMesh,
      side: 'right',
      position: [rx, ry, rz],
      ...(rEnd ? { segmentEnd: [rEnd[0], rEnd[1], rEnd[2]] } : {}),
      ...(rNorm ? { normal: [rNorm[0], rNorm[1], rNorm[2]] } : {}),
    },
    {
      id: `${spec.baseId}_l`,
      ...common,
      parentMesh: spec.lParentMesh,
      side: 'left',
      position: [Number((-rx).toFixed(4)), ry, rz],
      ...(rEnd ? { segmentEnd: [Number((-rEnd[0]).toFixed(4)), rEnd[1], rEnd[2]] } : {}),
      ...(rNorm ? { normal: [Number((-rNorm[0]).toFixed(4)), rNorm[1], rNorm[2]] } : {}),
    },
  ];
}

